CREATE TABLE IF NOT EXISTS INBAPS_USERS (
    ID TEXT PRIMARY KEY, USERNAME TEXT NOT NULL UNIQUE, DISPLAY_NAME TEXT NOT NULL,
    PASSWORD_HASH TEXT NOT NULL, ROLE TEXT NOT NULL CHECK (ROLE IN ('admin','analyst')), CREATED_AT TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS INBAPS_SESSIONS (
    TOKEN_HASH TEXT PRIMARY KEY, USER_ID TEXT NOT NULL REFERENCES INBAPS_USERS(ID),
    CSRF_TOKEN TEXT NOT NULL, EXPIRES_AT REAL NOT NULL
);
CREATE INDEX IF NOT EXISTS INBAPS_IX_SESSION_EXP ON INBAPS_SESSIONS(EXPIRES_AT);
CREATE TABLE IF NOT EXISTS INBAPS_RECORDS (
    ID TEXT PRIMARY KEY, KIND TEXT NOT NULL, OWNER_ID TEXT NOT NULL REFERENCES INBAPS_USERS(ID),
    PAYLOAD TEXT NOT NULL, CREATED_AT TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS INBAPS_IX_RECORD_OWNER ON INBAPS_RECORDS(OWNER_ID, KIND);
