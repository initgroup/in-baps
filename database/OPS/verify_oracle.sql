-- Read-only verification. Run as the same owner used for install_oracle.sql.
SELECT SYS_CONTEXT('USERENV', 'SESSION_USER') AS LOGIN_USER
     , SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA
  FROM DUAL;

SELECT OBJECT_NAME
     , OBJECT_TYPE
     , STATUS
  FROM USER_OBJECTS
 WHERE REGEXP_LIKE(OBJECT_NAME, '^INIT\$_(TB|VW|SP|IX|PK|UK|FK|CK)_BAPS_')
 ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT VERSION
     , CHECKSUM
     , APPLIED_AT
     , STATUS
  FROM INIT$_TB_BAPS_HISTORY
 ORDER BY VERSION;
