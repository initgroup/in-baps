-- [MIGRATION_LIST]
SELECT VERSION, CHECKSUM, APPLIED_AT, STATUS FROM INIT$_TB_BAPS_HISTORY ORDER BY VERSION
;
-- [MIGRATION_INSERT]
INSERT INTO INIT$_TB_BAPS_HISTORY (VERSION, CHECKSUM, APPLIED_AT, STATUS)
VALUES (:version, :checksum, :applied_at, 'RUNNING')
;
-- [MIGRATION_COMPLETE]
UPDATE INIT$_TB_BAPS_HISTORY
   SET STATUS = 'APPLIED'
     , APPLIED_AT = :applied_at
 WHERE VERSION = :version
;
-- [ORACLE_OBJECTS]
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM USER_OBJECTS
 WHERE REGEXP_LIKE(OBJECT_NAME, '^INIT\$_(TB|VW|SP|IX|PK|UK|FK|CK)_BAPS_')
 ORDER BY OBJECT_TYPE, OBJECT_NAME
;
-- [ORACLE_SCHEMA]
SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS SCHEMA_NAME FROM DUAL
;
