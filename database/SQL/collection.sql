-- [API_TARGET_COLUMNS]
SELECT C.COLUMN_NAME, C.DATA_TYPE, C.NULLABLE,
CASE WHEN EXISTS (SELECT 1 FROM USER_CONSTRAINTS K JOIN USER_CONS_COLUMNS KC
ON K.CONSTRAINT_NAME=KC.CONSTRAINT_NAME
WHERE K.TABLE_NAME=C.TABLE_NAME AND K.CONSTRAINT_TYPE='P' AND KC.COLUMN_NAME=C.COLUMN_NAME) THEN 1 ELSE 0 END,
C.DATA_PRECISION, C.DATA_SCALE, C.CHAR_USED, COALESCE(C.CHAR_LENGTH, 0)
FROM USER_TAB_COLUMNS C WHERE C.TABLE_NAME=:table_name ORDER BY C.COLUMN_ID
;
