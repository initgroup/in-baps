-- [API_JOB_DUE]
SELECT J.ID, J.OWNER_ID, J.SOURCE_ID, J.INTERVAL_SECONDS, J.NEXT_RUN_AT, U.ROLE
FROM INIT$_TB_BAPS_API_JOB J JOIN INIT$_TB_BAPS_MEMBER U ON U.ID=J.OWNER_ID
JOIN INIT$_TB_BAPS_API_SOURCE S ON S.ID=J.SOURCE_ID AND S.OWNER_ID=J.OWNER_ID
WHERE J.ENABLED=1 AND J.NEXT_RUN_AT<=:now AND S.LOCK_TOKEN IS NULL
AND (:job_id IS NULL OR J.ID=:job_id)
ORDER BY J.NEXT_RUN_AT, J.ID
FETCH FIRST 50 ROWS ONLY
;
-- [API_JOB_DUE_SQLITE]
SELECT J.ID, J.OWNER_ID, J.SOURCE_ID, J.INTERVAL_SECONDS, J.NEXT_RUN_AT, U.ROLE
FROM INIT$_TB_BAPS_API_JOB J JOIN INIT$_TB_BAPS_MEMBER U ON U.ID=J.OWNER_ID
JOIN INIT$_TB_BAPS_API_SOURCE S ON S.ID=J.SOURCE_ID AND S.OWNER_ID=J.OWNER_ID
WHERE J.ENABLED=1 AND J.NEXT_RUN_AT<=:now AND S.LOCK_TOKEN IS NULL
AND (:job_id IS NULL OR J.ID=:job_id)
ORDER BY J.NEXT_RUN_AT, J.ID LIMIT 50
;
