SELECT OBJECT_NAME AS NAME, OBJECT_TYPE AS TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_TYPE IN ('TABLE','VIEW','MATERIALIZED VIEW','PROCEDURE','FUNCTION','PACKAGE','TRIGGER','SEQUENCE','INDEX')
AND (:search IS NULL OR UPPER(OBJECT_NAME) LIKE :search)
ORDER BY OBJECT_TYPE, OBJECT_NAME
FETCH FIRST 1000 ROWS ONLY

