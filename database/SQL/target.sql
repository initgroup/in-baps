SELECT O.OBJECT_NAME, O.OBJECT_TYPE, O.STATUS, COALESCE(I.TABLE_NAME, T.TABLE_NAME) AS PARENT_TABLE
FROM USER_OBJECTS O
LEFT JOIN USER_INDEXES I ON O.OBJECT_TYPE='INDEX' AND I.INDEX_NAME=O.OBJECT_NAME
LEFT JOIN USER_TRIGGERS T ON O.OBJECT_TYPE='TRIGGER' AND T.TRIGGER_NAME=O.OBJECT_NAME
WHERE O.OBJECT_TYPE IN ('TABLE','VIEW','MATERIALIZED VIEW','PROCEDURE','FUNCTION','PACKAGE','TRIGGER','SEQUENCE','INDEX')
AND (:search IS NULL OR UPPER(O.OBJECT_NAME) LIKE :search ESCAPE '\')
ORDER BY O.OBJECT_TYPE, O.OBJECT_NAME

