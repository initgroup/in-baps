CASE WHEN EXISTS (SELECT 1 FROM USER_CONSTRAINTS K JOIN USER_CONS_COLUMNS KC
ON K.CONSTRAINT_NAME=KC.CONSTRAINT_NAME
WHERE K.TABLE_NAME=C.TABLE_NAME AND K.CONSTRAINT_TYPE='P' AND KC.COLUMN_NAME=C.COLUMN_NAME) THEN 1 ELSE 0 END AS PRIMARY_KEY,
C.DATA_LENGTH, C.DATA_PRECISION, C.DATA_SCALE
FROM USER_TAB_COLUMNS C WHERE C.TABLE_NAME=:table_name ORDER BY C.COLUMN_ID

