-- [USER_GET]
SELECT ID, USERNAME, DISPLAY_NAME, PASSWORD_HASH, ROLE
  FROM INIT$_TB_BAPS_MEMBER
 WHERE USERNAME = :username
;
-- [USER_INSERT]
INSERT INTO INIT$_TB_BAPS_MEMBER (ID, USERNAME, DISPLAY_NAME, PASSWORD_HASH, ROLE, CREATED_AT)
VALUES (:id, :username, :display_name, :password_hash, :role, :created)
;
-- [SESSION_INSERT]
INSERT INTO INIT$_TB_BAPS_SESSION
       (TOKEN_HASH, USER_ID, CSRF_TOKEN, EXPIRES_AT, IDLE_EXPIRES_AT, LAST_SEEN_AT)
VALUES (:token_hash, :user_id, :csrf_token, :expires, :idle_expires, :now)
;
-- [SESSION_GET]
SELECT U.ID, U.USERNAME, U.DISPLAY_NAME, U.ROLE, S.CSRF_TOKEN,
       S.EXPIRES_AT, S.IDLE_EXPIRES_AT, S.LAST_SEEN_AT
  FROM INIT$_TB_BAPS_SESSION S
  JOIN INIT$_TB_BAPS_MEMBER U ON U.ID = S.USER_ID
 WHERE S.TOKEN_HASH = :token_hash
   AND S.EXPIRES_AT > :now
   AND S.IDLE_EXPIRES_AT > :now
;
-- [SESSION_TOUCH]
UPDATE INIT$_TB_BAPS_SESSION
   SET LAST_SEEN_AT = CASE WHEN LAST_SEEN_AT > :now THEN LAST_SEEN_AT ELSE :now END,
       IDLE_EXPIRES_AT = CASE WHEN IDLE_EXPIRES_AT > :idle_expires THEN IDLE_EXPIRES_AT ELSE :idle_expires END
 WHERE TOKEN_HASH = :token_hash
   AND EXPIRES_AT > :now
   AND IDLE_EXPIRES_AT > :now
;
-- [SESSION_DELETE]
DELETE FROM INIT$_TB_BAPS_SESSION WHERE TOKEN_HASH = :token_hash
;
-- [SESSION_CLEAN]
DELETE FROM INIT$_TB_BAPS_SESSION WHERE EXPIRES_AT <= :now OR IDLE_EXPIRES_AT <= :now
;
