-- [ANALYSIS_LIST]
SELECT JSON_MERGEPATCH(PAYLOAD, '{"result":null}' RETURNING CLOB ERROR ON ERROR) AS PAYLOAD
  FROM INIT$_TB_BAPS_RECORD
 WHERE KIND = 'analysis' AND OWNER_ID = :owner
 ORDER BY CREATED_AT DESC, ID
 FETCH FIRST 200 ROWS ONLY
;
-- [ANALYSIS_LIST_SQLITE]
SELECT JSON_REMOVE(PAYLOAD, '$.result') AS PAYLOAD
  FROM INIT$_TB_BAPS_RECORD
 WHERE KIND = 'analysis' AND OWNER_ID = :owner
 ORDER BY CREATED_AT DESC, ID
 LIMIT 200
;
